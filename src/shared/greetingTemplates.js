// 把一段随机挑选写成可复现的：同样的 seed 得到同样的结果。
// 这样测试才能断言输出，界面上的"换一个说法"也只是换一个 seed。
//
// 注意不能写成 seed / salt 取整那种偷懒做法——seed 小的时候整除结果全是 0，
// 三个位置会一起卡在第一项，看上去就像"只有开头在变"。
// 这里先把 seed 和 salt 混成一个散列值，各个位置才真正独立。
function pick(list, seed, salt) {
  if (!list || !list.length) return ''
  let hash = (Math.abs(Math.floor(seed)) ^ (salt * 0x9e3779b9)) >>> 0
  hash = Math.imul(hash ^ (hash >>> 16), 0x45d9f3b) >>> 0
  hash = Math.imul(hash ^ (hash >>> 16), 0x45d9f3b) >>> 0
  // 末尾这个 >>> 0 不能省：^ 的结果是**有符号** 32 位整数，可能是负数，
  // 负数取余会得到负下标，list[-3] 就是 undefined，文案里会冒出 "undefined"。
  return list[((hash ^ (hash >>> 16)) >>> 0) % list.length]
}

/**
 * 拼出一条完整祝福。
 *
 * @param input  { receiver, occasion, tone, details }
 * @param seed   随机种子。不传就用当前时间，**传同一个值结果完全一样**。
 *               界面上的"换一个说法"就是换一个 seed 再调一次。
 */
export function composeGreeting(input = {}, seed = Date.now()) {
  const occasion = OCCASION_META[input.occasion] ? input.occasion : '通用'
  const tone = OPENINGS[input.tone] ? input.tone : '温暖'
  const receiver = String(input.receiver || '').trim()
  const details = String(input.details || '').trim()

  const opening = pick(OPENINGS[tone], seed, 1)
  const body = pick(BODIES[occasion][tone], seed, 7)
  const closing = pick(CLOSINGS[tone], seed, 13)

  // 补充信息不是硬塞在最后，而是承上启下地接进去
  const bridge = details ? `也愿"${details.slice(0, 40)}"成为值得珍藏的记忆。` : ''

  // 「简洁」风格就该简洁：不加开头、不加破折号，一句话说完。
  const main = tone === '简洁' ? body : `${opening}——${body}`

  const lines = [receiver ? `${receiver}：` : '', main, bridge, closing].filter(Boolean)

  return lines.join('\n')
}

// 这一版还剩多少种组合，用来在界面上告诉学生"它真的在换"
export function variantCount() {
  let total = 0
  for (const occasion of Object.keys(BODIES))
    for (const tone of Object.keys(BODIES[occasion]))
      total += BODIES[occasion][tone].length * OPENINGS[tone].length * CLOSINGS[tone].length
  return total
}
